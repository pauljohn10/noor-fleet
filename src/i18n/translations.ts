export function translateDynamicEnToAr(text: string): string {
  const trimmed = text.trim();
  if (!trimmed) return text;

  // EXPIRED (5d ago)
  const expiredMatch = trimmed.match(/^EXPIRED\s*\((\d+)d\s*ago\)$/i);
  if (expiredMatch) return `منتهي (منذ ${expiredMatch[1]} يوم)`;

  // EXPIRING IN X DAYS / EXPIRING (Xd)
  const expiringDaysMatch = trimmed.match(/^EXPIRING\s+IN\s+(\d+)\s+DAYS?$/i);
  if (expiringDaysMatch) return `ينتهي خلال ${expiringDaysMatch[1]} يوم`;

  // VALID (Xd left)
  const validLeftMatch = trimmed.match(/^VALID\s*\((\d+)d\s*left\)$/i);
  if (validLeftMatch) return `ساري (${validLeftMatch[1]} يوم متبقي)`;

  // Time ago: 15s ago, 5m ago, 3h ago, 2d ago
  const secAgo = trimmed.match(/^(\d+)s\s+ago$/i);
  if (secAgo) return `منذ ${secAgo[1]} ث`;
  const minAgo = trimmed.match(/^(\d+)m\s+ago$/i);
  if (minAgo) return `منذ ${minAgo[1]} د`;
  const hrAgo = trimmed.match(/^(\d+)h\s+ago$/i);
  if (hrAgo) return `منذ ${hrAgo[1]} س`;
  const dayAgo = trimmed.match(/^(\d+)d\s+ago$/i);
  if (dayAgo) return `منذ ${dayAgo[1]} ي`;

  // +X critical / +X active
  const plusCritical = trimmed.match(/^\+(\d+)\s+critical$/i);
  if (plusCritical) return `+${plusCritical[1]} حرج`;

  // X New
  const countNew = trimmed.match(/^(\d+)\s+New$/i);
  if (countNew) return `${countNew[1]} جديد`;

  // X expired, X expiring
  const expiredComma = trimmed.match(/^(\d+)\s+expired$/i);
  if (expiredComma) return `${expiredComma[1]} منتهي`;
  const expiringComma = trimmed.match(/^(\d+)\s+expiring$/i);
  if (expiringComma) return `${expiringComma[1]} قريب الانتهاء`;

  return text;
}

export function lookupTranslation(
  key: string,
  language: Language,
  fallback?: string
): string {
  // 1. Direct structured translation key match
  if (STRUCTURED_TRANSLATIONS[key]?.[language]) {
    return STRUCTURED_TRANSLATIONS[key][language];
  }

  // 2. Normalized key match in STRUCTURED_TRANSLATIONS
  const trimmedKey = key.trim();
  const upperKey = trimmedKey.toUpperCase();
  const underscoreKey = upperKey.replace(/\s+/g, '_');

  if (STRUCTURED_TRANSLATIONS[trimmedKey]?.[language]) {
    return STRUCTURED_TRANSLATIONS[trimmedKey][language];
  }
  if (STRUCTURED_TRANSLATIONS[upperKey]?.[language]) {
    return STRUCTURED_TRANSLATIONS[upperKey][language];
  }
  if (STRUCTURED_TRANSLATIONS[underscoreKey]?.[language]) {
    return STRUCTURED_TRANSLATIONS[underscoreKey][language];
  }

  // 3. If English, return fallback or key
  if (language === 'en') {
    return fallback !== undefined ? fallback : key;
  }

  // 4. Arabic lookup against phrase dictionary (check key first, then fallback)
  const candidates = [trimmedKey, upperKey, underscoreKey, upperKey.replace(/_/g, ' ')];
  if (fallback) {
    const fbTrim = fallback.trim();
    candidates.push(fbTrim, fbTrim.toUpperCase(), fbTrim.toUpperCase().replace(/\s+/g, '_'));
  }

  for (const candidate of candidates) {
    if (EN_TO_AR_PHRASES[candidate]) {
      return EN_TO_AR_PHRASES[candidate];
    }
    const lower = candidate.toLowerCase();
    if (LOWERCASE_EN_TO_AR[lower]) {
      return LOWERCASE_EN_TO_AR[lower];
    }
  }

  // 5. Try dynamic pattern translation
  const target = fallback !== undefined ? fallback : key;
  const dynamic = translateDynamicEnToAr(target);
  if (dynamic !== target) {
    return dynamic;
  }

  return target;
}
